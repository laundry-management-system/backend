-- 031: hình thức giặt động (wash_modes) thay cho NORMAL / EXPRESS cố định. Không đổi tiền, không đổi due_at của đơn cũ.
-- Chạy TRƯỚC KHI khởi động BE 031: dừng BE cũ -> chạy script -> khởi động BE mới (quickstart bước 2).
--
-- TRƯỚC KHI CHẠY: sao lưu DB:
--   pg_dump -Fc -f before-031.dump "$DB_URL"
-- Khôi phục nếu cần: pg_restore --clean -d "$DB_URL" before-031.dump
--
-- Chạy:   psql "$DB_URL" -v ON_ERROR_STOP=1 -f backend/scripts/migrate-031-wash-modes.sql
-- Dev:    docker exec -i laundry-postgres psql -U laundry -d laundry -v ON_ERROR_STOP=1 < backend/scripts/migrate-031-wash-modes.sql
-- Chạy lại bao nhiêu lần cũng được (không thêm hình thức / liên kết trùng, không ghi đè giá đã sửa ở BE mới).
--
-- Quay lại BE cũ không mất dữ liệu (thay vì restore dump): dừng BE mới, chạy backend/scripts/rollback-031-wash-modes.sql,
-- rồi khởi động BE cũ. Xem giới hạn khi migrate lại ở đầu file rollback.

\set ON_ERROR_STOP on

BEGIN;

-- 1. Bảng mới (kiểu cột như Hibernate sinh, để ddl-auto: update không đổi thêm).
CREATE TABLE IF NOT EXISTS wash_modes (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       timestamp(6) with time zone NOT NULL,
    updated_at       timestamp(6) with time zone NOT NULL,
    name             varchar(50) NOT NULL,
    completion_hours integer NOT NULL,
    sort_order       integer NOT NULL DEFAULT 0,
    active           boolean NOT NULL DEFAULT true,
    is_default       boolean NOT NULL DEFAULT false
);
-- sort_order không còn map vào entity (FR-034): bảng do Hibernate tạo trước đó có NOT NULL không default -> thêm default để INSERT từ BE không lỗi.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = current_schema() AND table_name = 'wash_modes' AND column_name = 'sort_order') THEN
        ALTER TABLE wash_modes ALTER COLUMN sort_order SET DEFAULT 0;
    END IF;
END $$;
-- Chỉ script dùng (không map vào entity): nhận ra hình thức sinh từ NORMAL / EXPRESS khi chạy lại / hoàn tác.
ALTER TABLE wash_modes ADD COLUMN IF NOT EXISTS legacy_order_type varchar(20);
CREATE UNIQUE INDEX IF NOT EXISTS uk_wash_modes_name_ci ON wash_modes (lower(name));
-- Đúng một hình thức mặc định (FR-001c); chặn cả khi hai Admin đổi mặc định cùng lúc
CREATE UNIQUE INDEX IF NOT EXISTS uk_wash_modes_single_default ON wash_modes (is_default) WHERE is_default;

CREATE TABLE IF NOT EXISTS service_wash_modes (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamp(6) with time zone NOT NULL,
    updated_at   timestamp(6) with time zone NOT NULL,
    service_id   bigint NOT NULL,
    wash_mode_id bigint NOT NULL,
    price        numeric(12,0) NOT NULL
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uk_service_wash_modes') THEN
        ALTER TABLE service_wash_modes ADD CONSTRAINT uk_service_wash_modes UNIQUE (service_id, wash_mode_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_service_wash_modes_service') THEN
        ALTER TABLE service_wash_modes ADD CONSTRAINT fk_service_wash_modes_service FOREIGN KEY (service_id) REFERENCES services (id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_service_wash_modes_wash_mode') THEN
        ALTER TABLE service_wash_modes ADD CONSTRAINT fk_service_wash_modes_wash_mode FOREIGN KEY (wash_mode_id) REFERENCES wash_modes (id);
    END IF;
END $$;

-- 2. Hai hình thức từ NORMAL / EXPRESS: đã có theo legacy_order_type thì bỏ qua; trùng tên thì gán legacy_order_type; không thì tạo.
DO $$
DECLARE
    r record;
    hours integer;
BEGIN
    FOR r IN SELECT * FROM (VALUES
        ('NORMAL',  'Tiêu chuẩn', 'BOOKING_RETURN_GAP_HOURS_NORMAL',  24, 1, true),
        ('EXPRESS', 'Giặt nhanh', 'BOOKING_RETURN_GAP_HOURS_EXPRESS',  6, 2, false)
    ) v(order_type, name, gap_key, fallback_hours, sort_order, is_default) LOOP
        CONTINUE WHEN EXISTS (SELECT 1 FROM wash_modes WHERE legacy_order_type = r.order_type);

        UPDATE wash_modes SET legacy_order_type = r.order_type WHERE lower(name) = lower(r.name);
        CONTINUE WHEN FOUND;

        SELECT setting_value::integer INTO hours
          FROM settings WHERE setting_key = r.gap_key AND setting_value ~ '^\s*[0-9]+\s*$';

        INSERT INTO wash_modes (created_at, updated_at, name, completion_hours, sort_order, active, is_default, legacy_order_type)
        VALUES (now(), now(), r.name, COALESCE(hours, r.fallback_hours), r.sort_order, true,
                r.is_default AND NOT EXISTS (SELECT 1 FROM wash_modes WHERE is_default), r.order_type);
    END LOOP;
END $$;

-- 4. Cột hình thức trên đơn (trước bước 3 / 4a vì 4a ghi vào các cột này).
ALTER TABLE orders
    ADD COLUMN IF NOT EXISTS wash_mode_id bigint,
    ADD COLUMN IF NOT EXISTS wash_mode_name varchar(50),
    ADD COLUMN IF NOT EXISTS wash_mode_hours integer,
    ADD COLUMN IF NOT EXISTS requested_service_prices jsonb,
    ADD COLUMN IF NOT EXISTS legacy_service_surcharges jsonb;

-- Backfill theo order_type (null hoặc giá trị lạ -> NORMAL). Không đụng cột tiền / due_at.
UPDATE orders o
   SET wash_mode_id = m.id, wash_mode_name = m.name, wash_mode_hours = m.completion_hours
  FROM wash_modes m
 WHERE o.wash_mode_id IS NULL
   AND m.legacy_order_type = CASE WHEN o.order_type = 'EXPRESS' THEN 'EXPRESS' ELSE 'NORMAL' END;

ALTER TABLE orders
    ALTER COLUMN wash_mode_id SET NOT NULL,
    ALTER COLUMN wash_mode_name SET NOT NULL,
    ALTER COLUMN wash_mode_hours SET NOT NULL;

-- Đơn mới có order_type NULL nên uk_orders_intake_request_type (intake_request_id, order_type) không còn chặn trùng.
CREATE UNIQUE INDEX IF NOT EXISTS uk_orders_intake_request_new ON orders (intake_request_id) WHERE order_type IS NULL AND intake_request_id IS NOT NULL;

-- 3 + 4a. Cần các cột giá cũ của services; DB không có chúng (DB mới do BE 031 tạo) thì bỏ qua.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = current_schema() AND table_name = 'services' AND column_name = 'current_price') THEN
        -- 3. Liên kết giá, chỉ cho dịch vụ chưa có liên kết nào. Một câu lệnh để NOT EXISTS thấy cùng một trạng thái.
        EXECUTE $q$
            INSERT INTO service_wash_modes (created_at, updated_at, service_id, wash_mode_id, price)
            SELECT now(), now(), s.id, m.id,
                   CASE m.legacy_order_type WHEN 'EXPRESS' THEN s.current_price + COALESCE(s.express_surcharge, 0)
                                            ELSE s.current_price END
              FROM services s
              JOIN wash_modes m ON m.legacy_order_type = 'NORMAL'
                                OR (m.legacy_order_type = 'EXPRESS' AND s.express_supported)
             WHERE s.current_price IS NOT NULL
               AND NOT EXISTS (SELECT 1 FROM service_wash_modes l WHERE l.service_id = s.id)
        $q$;

        -- 4a. Đơn v3 chưa phân loại: chụp giá cũ (và phụ phí cũ với đơn EXPRESS) để phân loại ra đúng tiền như trước.
        EXECUTE $q$
            UPDATE orders o
               SET requested_service_prices = COALESCE(
                       (SELECT jsonb_object_agg(s.id, s.current_price)
                          FROM services s
                         WHERE s.current_price IS NOT NULL
                           AND s.id IN (SELECT jsonb_array_elements_text(o.requested_service_ids)::bigint)),
                       '{}'::jsonb),
                   legacy_service_surcharges = CASE WHEN o.order_type = 'EXPRESS' THEN COALESCE(
                       (SELECT jsonb_object_agg(s.id, s.express_surcharge)
                          FROM services s
                         WHERE s.express_supported AND s.express_surcharge IS NOT NULL
                           AND s.id IN (SELECT jsonb_array_elements_text(o.requested_service_ids)::bigint)),
                       '{}'::jsonb) END
             WHERE o.intake_code IS NOT NULL
               AND o.order_type IS NOT NULL
               AND o.requested_service_prices IS NULL
               AND NOT EXISTS (SELECT 1 FROM order_items i WHERE i.order_id = o.id)
        $q$;
    END IF;
END $$;

-- 5. Cột cũ thành nullable (BE mới không ghi). orders.service_type vốn đã nullable; giữ cho chắc ăn.
DO $$
DECLARE
    col text[];
BEGIN
    FOREACH col SLICE 1 IN ARRAY ARRAY[
        ['orders', 'order_type'],
        ['orders', 'service_type'],
        ['services', 'current_price'],
        ['services', 'standard_hours'],
        ['services', 'express_supported']
    ] LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = current_schema() AND table_name = col[1] AND column_name = col[2]) THEN
            EXECUTE format('ALTER TABLE %I ALTER COLUMN %I DROP NOT NULL', col[1], col[2]);
        END IF;
    END LOOP;
END $$;

-- 5a. Mã hình thức HTxx (cùng kết quả với String.format("HT%02d", id) ở BE).
ALTER TABLE wash_modes ADD COLUMN IF NOT EXISTS code varchar(10);
UPDATE wash_modes SET code = 'HT' || lpad(id::text, 2, '0') WHERE code IS NULL;
ALTER TABLE wash_modes ALTER COLUMN code SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uk_wash_modes_code ON wash_modes (code);

-- 6. Giờ trả theo hình thức nay nằm trên wash_modes (đã đọc ở bước 2).
DELETE FROM settings WHERE setting_key IN ('BOOKING_RETURN_GAP_HOURS_NORMAL', 'BOOKING_RETURN_GAP_HOURS_EXPRESS');

COMMIT;
